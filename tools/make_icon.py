"""MRI Rehearsal icon (design `appIcon`): one set of polygons drawn two ways, so they always match: the adaptive-icon
foreground vector (`res/drawable/ic_launcher_foreground.xml`), the legacy launcher PNG and the 512 export for the
factory gallery.

    python tools/make_icon.py <export-512.png>

Magnet deep blue tile #17324D; a thick white ring (the bore) a little above centre; inside it a small warm beige
#F2E6D0 head lying on its back in profile (face up, neck running to the right, into the bore); outside the ring at the
right three short pale blue #9FC5E8 arcs (the noise). No text, no gradient. Coordinates are the vector's
108-unit viewport (safe zone: circle of radius 33 around 54,54).
"""
import math
import os
import sys

from PIL import Image, ImageDraw

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
RES = os.path.join(ROOT, "app", "src", "main", "res")
BLUE = (0x17, 0x32, 0x4D, 255)
WHITE = (255, 255, 255, 255)
BEIGE = (0xF2, 0xE6, 0xD0, 255)
PALE = (0x9F, 0xC5, 0xE8, 255)

RING_C = (51.0, 49.0)
RING_R_OUT = 23.5
RING_R_IN = 16.5


def circle(cx, cy, r, n=72, a0=0.0, a1=360.0):
    return [(cx + r * math.cos(math.radians(a0 + (a1 - a0) * i / n)), cy + r * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]


def band(cx, cy, r_in, r_out, a0, a1, n=24):
    """Thick arc as a closed polygon: outer edge forward, inner edge back."""
    return circle(cx, cy, r_out, n, a0, a1) + circle(cx, cy, r_in, n, a0, a1)[::-1]


HEAD_C = (46.5, 52.0)
HEAD_R = 7.2


def head():
    """Face and neck of a head lying face up, seen from the side (the skull is the circle HEAD_C / HEAD_R):
    forehead, nose, lips and chin on top, the neck running right into the bore."""
    cx, cy = HEAD_C
    return [(cx, cy - HEAD_R), (50.8, 45.3), (53.6, 43.0), (54.7, 45.8), (55.5, 47.4), (55.0, 49.2), (57.0, 50.0), (64.0, 50.0), (64.0, 57.0), (cx, cy + HEAD_R)]


def circle_path(c, r, fmt):
    cx, cy = c
    return f"M{fmt(cx - r)},{fmt(cy)}a{fmt(r)},{fmt(r)} 0,1 1,{fmt(2 * r)},0a{fmt(r)},{fmt(r)} 0,1 1,{fmt(-2 * r)},0z"


def ring_path(fmt):
    return circle_path(RING_C, RING_R_OUT, fmt) + circle_path(RING_C, RING_R_IN, fmt)


# sound waves leaving the bore to the right (kept short and level so the ring never reads as a magnifier handle)
ARCS = [band(RING_C[0], RING_C[1], r, r + 2.6, -a, a) for r, a in ((27.0, 26), (31.5, 20), (36.0, 14))]


def vector():
    def fmt(v):
        return f"{v:.2f}".rstrip("0").rstrip(".")

    def poly(pts):
        return "M" + "L".join(f"{fmt(x)},{fmt(y)}" for x, y in pts) + "Z"

    out = [
        '<?xml version="1.0" encoding="utf-8"?>\n',
        "<!-- MRI Rehearsal: white bore ring, a beige head lying face up inside it, three pale blue noise arcs "
        "(design appIcon); generated by tools/make_icon.py -->\n",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n',
        f'    <path\n        android:fillColor="#FFFFFFFF"\n        android:fillType="evenOdd"\n        android:pathData="{ring_path(fmt)}" />\n',
        f'    <path\n        android:fillColor="#FFF2E6D0"\n        android:pathData="{circle_path(HEAD_C, HEAD_R, fmt)}" />\n',
        f'    <path\n        android:fillColor="#FFF2E6D0"\n        android:pathData="{poly(head())}" />\n',
    ]
    for arc in ARCS:
        out.append(f'    <path\n        android:fillColor="#FF9FC5E8"\n        android:pathData="{poly(arc)}" />\n')
    out.append("</vector>\n")
    return "".join(out)


def raster(size, rounded):
    k = 8
    S = size * k
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if rounded:
        d.rounded_rectangle([0, 0, S - 1, S - 1], radius=int(S * 0.22), fill=BLUE)
    else:
        d.rectangle([0, 0, S, S], fill=BLUE)
    u = S / 108.0
    cx, cy = RING_C
    d.ellipse([(cx - RING_R_OUT) * u, (cy - RING_R_OUT) * u, (cx + RING_R_OUT) * u, (cy + RING_R_OUT) * u], fill=WHITE)
    d.ellipse([(cx - RING_R_IN) * u, (cy - RING_R_IN) * u, (cx + RING_R_IN) * u, (cy + RING_R_IN) * u], fill=BLUE)
    hx, hy = HEAD_C
    d.ellipse([(hx - HEAD_R) * u, (hy - HEAD_R) * u, (hx + HEAD_R) * u, (hy + HEAD_R) * u], fill=BEIGE)
    d.polygon([(x * u, y * u) for x, y in head()], fill=BEIGE)
    for arc in ARCS:
        d.polygon([(x * u, y * u) for x, y in arc], fill=PALE)
    return img.resize((size, size), Image.LANCZOS)


def main():
    with open(os.path.join(RES, "drawable", "ic_launcher_foreground.xml"), "w", encoding="utf-8") as f:
        f.write(vector())
    os.makedirs(os.path.join(RES, "mipmap-xxxhdpi"), exist_ok=True)
    raster(192, rounded=False).save(os.path.join(RES, "mipmap-xxxhdpi", "ic_launcher.png"))
    if len(sys.argv) > 1:
        raster(512, rounded=True).save(sys.argv[1])
        print("wrote", sys.argv[1])


if __name__ == "__main__":
    main()
